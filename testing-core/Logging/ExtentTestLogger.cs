using AventStack.ExtentReports;
using AventStack.ExtentReports.Reporter;
using AventStack.ExtentReports.Reporter.Config;
using core.Logging.Interfaces;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace testing_core.Logging
{
    /// <summary>
    /// Implements the <see cref="ITestLogger"/> interface using ExtentReports
    /// to log test events to a structured HTML report.
    /// </summary>
    public class ExtentTestLogger : ITestLogger
    {
        private readonly ExtentReports extentReports;

        /// <summary>
        /// currentTest is an instance of ExtentTest that represents the current test being logged.
        /// currentTest is initialized to null, and
        /// the first time NewLog is called, it will create a new ExtentTest instance and assign it to currentTest.
        /// </summary>
        private ExtentTest? currentTest;

        public ExtentTestLogger(ExtentReports extentReports)
        {
            this.extentReports = extentReports;

            // "TestReport.html" is the name of the HTML report file that will be generated by ExtentReports.
            // If we want to generate the report type different than HTML,
            // we can use other reporters provided by ExtentReports, such as ExtentV3HtmlReporter, ExtentXReporter, etc. 
            ExtentSparkReporter sparkReporter = new ExtentSparkReporter("TestReport.html");

            this.extentReports.AttachReporter(sparkReporter);
        }

        /// <summary>
        /// Start a new test log with the given test name. This will create a new ExtentTest instance
        /// </summary>
        /// <param name="testName">The name of the test to be logged.</param>
        public void NewLog(string testName)
        {
            currentTest = extentReports.CreateTest(testName);
        }

        /// <summary>
        /// Phải gọi extentReports.Flush() ở cuối thì dữ liệu mới được ghi vào file HTML
        /// </summary>
        public void Flush()
        {
            extentReports.Flush();
        }

        public void LogError(Exception ex)
        {
            currentTest?.Log(Status.Error, ex);
        }

        public void LogFail(string message)
        {
            currentTest?.Log(Status.Fail, message);
        }

        public void LogInfo(string message)
        {
            currentTest?.Log(Status.Info, message);
        }

        public void LogPass(string message)
        {
            currentTest?.Log(Status.Pass, message);
        }

        public void LogScreenshot(string base64EncodedScreenshotImage)
        {
            currentTest?.AddScreenCaptureFromBase64String(base64EncodedScreenshotImage);
        }

        public void LogWarning(string message)
        {
            currentTest?.Log(Status.Warning, message);
        }
    }
}
